#!/usr/bin/env node
/**
 * Capture the paired DSH browser page at a touch viewport for documentation and review.
 * The default output is a fresh temporary directory. An existing named capture
 * is replaced only with --overwrite; pairing input values are masked.
 *
 *   npm run capture:screenshots
 *   npm run capture:screenshots -- --out /tmp/shots
 *   npm run capture:screenshots -- --tarball ./dsh-mobile-0.5.5.tgz --out /tmp/shots --overwrite
 *
 * Use DSH_BOOT_SMOKE_BIN for a separate DSH runtime without another Mobile bundle.
 */
import { constants } from 'node:fs'
import { lstat, mkdir, mkdtemp, open, readFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { chromium } from 'playwright'
import { packBundle } from './packed-profile.mjs'
import {
  CLIENT_TIMEOUT_MS, createMobileProfile, dismissOnboarding, launchDsh,
  openPairing, pairMobilePage, removeTemporaryRoot, sanitized,
} from './mobile-boot-fixture.mjs'

const repository = fileURLToPath(new URL('..', import.meta.url))
const dshBin = resolve(process.env.DSH_BOOT_SMOKE_BIN
  ?? fileURLToPath(new URL('../node_modules/@deepseek-ai/dsh/lib/bin.js', import.meta.url)))
const PHONE_VIEWPORT = { width: 390, height: 844 }
const CAPTURE_NAMES = [
  'mobile-shell-01-pairing', 'mobile-shell-02-conversation',
  'mobile-shell-03-session-drawer', 'mobile-shell-04-settings',
]

/** Parse output choices before acquiring a profile or writing any images. */
export function parseCaptureOptions(args) {
  const options = { overwrite: false }
  const seen = new Set()
  for (let index = 0; index < args.length; index++) {
    const flag = args[index]
    if (!['--out', '--tarball', '--overwrite'].includes(flag)) throw new Error(`Unsupported option: ${String(flag)}`)
    if (seen.has(flag)) throw new Error(`Repeated option: ${flag}`)
    seen.add(flag)
    if (flag === '--overwrite') { options.overwrite = true; continue }
    const value = args[++index]
    if (typeof value !== 'string' || value.trim() === '' || value.startsWith('--')) {
      throw new Error(`${flag} requires a value`)
    }
    options[flag === '--out' ? 'outputDir' : 'tarball'] = resolve(value)
  }
  return options
}

/** Refuse replacement of linked output files, and require explicit overwrite for existing captures. */
async function assertOutputFile(path, overwrite) {
  let metadata
  try { metadata = await lstat(path, { bigint: true }) } catch (error) {
    if (error.code === 'ENOENT') return
    throw error
  }
  if (metadata.isSymbolicLink() || !metadata.isFile()) throw new Error(`Capture output is not a regular file: ${path}`)
  if (!overwrite) throw new Error(`Capture already exists: ${path}; use --overwrite to replace it`)
  return metadata
}

/** Use a fresh output directory unless a destination was explicitly selected. */
export async function prepareCaptureOutput({ outputDir, overwrite }) {
  const directory = outputDir ?? await mkdtemp(join(tmpdir(), 'dsh-mobile-screenshots-'))
  await mkdir(directory, { recursive: true })
  for (const name of CAPTURE_NAMES) await assertOutputFile(join(directory, `${name}.png`), overwrite)
  return directory
}

/** Save generated bytes exclusively unless replacement was explicitly requested. */
export async function writeCapture(path, bytes, overwrite) {
  const observed = await assertOutputFile(path, overwrite)
  const file = await open(path, observed === undefined ? 'wx' : constants.O_WRONLY | (constants.O_NOFOLLOW ?? 0))
  try {
    if (observed !== undefined) {
      const opened = await file.stat({ bigint: true })
      const current = await lstat(path, { bigint: true })
      if (!opened.isFile() || current.isSymbolicLink()
        || opened.dev !== observed.dev || opened.ino !== observed.ino
        || current.dev !== opened.dev || current.ino !== opened.ino) {
        throw new Error(`Capture output changed before overwrite: ${path}`)
      }
      await file.truncate(0)
    }
    await file.writeFile(bytes)
  } finally { await file.close() }
}

/** Capture a ready surface while excluding the temporary authentication value. */
export async function screenshotMobilePage(phone) {
  await phone.evaluate(async () => { await document.fonts.ready })
  return phone.screenshot({
    animations: 'disabled',
    mask: [phone.locator('#pair-token')],
    maskColor: '#e2e8f0',
  })
}

async function capture(baseUrl, logs, outputDir, overwrite) {
  const browser = await chromium.launch({ headless: true })
  const written = []
  try {
    const desktop = await browser.newPage()
    const pairUrl = await openPairing(desktop, baseUrl, logs)
    const phone = await browser.newPage({
      viewport: PHONE_VIEWPORT, isMobile: true, hasTouch: true, reducedMotion: 'reduce', deviceScaleFactor: 2,
    })
    const shot = async name => {
      const path = join(outputDir, `${name}.png`)
      await writeCapture(path, await screenshotMobilePage(phone), overwrite)
      written.push(path)
      console.log(`  captured ${name}.png`)
    }
    const workspace = await pairMobilePage(phone, pairUrl, logs, {
      beforeSubmit: () => shot('mobile-shell-01-pairing'),
    })
    await dismissOnboarding(phone)
    await phone.locator('.dshm-main').waitFor({ state: 'visible', timeout: CLIENT_TIMEOUT_MS })
    await shot('mobile-shell-02-conversation')

    const drawer = phone.locator('.dshm-drawer')
    await drawer.locator('button[data-dsh-mobile-toggle]').click()
    await phone.waitForFunction(() => document.querySelector('.dshm-scrim')?.getAttribute('data-open') === 'true')
    await drawer.locator('[data-dsh-mobile-sidebar-root]').waitFor({ state: 'visible', timeout: CLIENT_TIMEOUT_MS })
    await shot('mobile-shell-03-session-drawer')

    await drawer.locator('button[aria-haspopup="dialog"]').first().click()
    const settings = phone.locator('[role="dialog"][aria-modal="true"]').first()
    await settings.waitFor({ state: 'visible', timeout: CLIENT_TIMEOUT_MS })
    await shot('mobile-shell-04-settings')
    console.log(`  verified ${String(workspace.workspaces)} Workspaces over the real WebSocket`)
    return written
  } finally { await browser.close() }
}

async function main() {
  const options = parseCaptureOptions(process.argv.slice(2))
  await readFile(dshBin).catch(error => {
    if (error.code === 'ENOENT') throw new Error(`DSH CLI not found at ${dshBin}; set DSH_BOOT_SMOKE_BIN`)
    throw error
  })
  const outputDir = await prepareCaptureOutput(options)
  const root = await mkdtemp(join(tmpdir(), 'dsh-mobile-capture-'))
  let dsh
  const failures = []
  try {
    const tarball = options.tarball ?? (process.env.DSH_BOOT_SMOKE_MOBILE_TARBALL === undefined
      ? await packBundle(repository, root) : resolve(process.env.DSH_BOOT_SMOKE_MOBILE_TARBALL))
    const home = await createMobileProfile(root, { tarball, dshBin })
    dsh = launchDsh(root, home, dshBin)
    const written = await capture(await dsh.ready(), dsh.logs, outputDir, options.overwrite)
    console.log(`\n${String(written.length)} screenshots written to ${outputDir}`)
  } catch (error) {
    failures.push(new Error(sanitized(error instanceof Error ? error.stack ?? error.message : String(error))))
  } finally {
    if (dsh !== undefined) {
      try {
        const result = await dsh.close()
        if (result.forced || (result.code !== 0 && result.signal !== 'SIGTERM')) {
          failures.push(new Error(`DSH did not stop quiescently: ${JSON.stringify(result)}\n${dsh.logs()}`))
        }
      } catch (error) { failures.push(error) }
    }
    try { await removeTemporaryRoot(root, 'dsh-mobile-capture-') } catch (error) { failures.push(error) }
  }
  if (failures.length === 1) throw failures[0]
  if (failures.length > 1) throw new AggregateError(failures, 'Mobile screenshot capture and cleanup failed')
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main()
